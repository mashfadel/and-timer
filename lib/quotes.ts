/**
 * A no-repeat deck. Shuffle once, deal until empty, reshuffle — so a single
 * session never shows the same line twice while the bank still has lines left.
 */
export function makeDeck(source: readonly Quote[] = QUOTES): () => Quote {
  let pile: Quote[] = [];
  let last: Quote | null = null;

  const refill = () => {
    pile = [...source];
    // Fisher-Yates.
    for (let i = pile.length - 1; i > 0; i -= 1) {
      const j = Math.floor(Math.random() * (i + 1));
      [pile[i], pile[j]] = [pile[j], pile[i]];
    }
    // Never open a new pile on the line that closed the last one.
    if (last && pile.length > 1 && pile[pile.length - 1].t === last.t) {
      [pile[0], pile[pile.length - 1]] = [pile[pile.length - 1], pile[0]];
    }
  };

  return () => {
    if (pile.length === 0) refill();
    const next = pile.pop() as Quote;
    last = next;
    return next;
  };
}
